#!/usr/bin/env python3
"""EXP-73 stage-0 teacher-wave / scheduled on-policy distillation.

This runner distills trajectories generated by the healthy scalar-time ELF
teacher.  It is intentionally independent of the OWT loader: the teacher's
paired noise-to-text trajectories are the training data for this sampler
distillation stage.
"""

import argparse
import json
import math
import sys
from pathlib import Path

import torch
import torch.nn.functional as F


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
SRC = REPO_ROOT / "src"
for path in (str(SRC), str(HERE)):
    if path not in sys.path:
        sys.path.insert(0, path)

import unified_method_eval_exp64 as common
from modules.model import ELF_B
from utils.sampling_utils import _ode_step, get_sampling_steps, net_out_to_v_x


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--student_checkpoint", required=True)
    parser.add_argument(
        "--teacher_checkpoint",
        default="converted/elf_b-owt-baseline_torch.pt",
    )
    parser.add_argument("--mode", choices=("teacher_wave", "on_policy"), required=True)
    parser.add_argument("--output_dir", required=True)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--steps", type=int, default=200)
    parser.add_argument("--batch_size", type=int, default=4)
    parser.add_argument("--max_length", type=int, default=128)
    parser.add_argument("--teacher_steps", type=int, default=16)
    parser.add_argument("--unroll_steps", type=int, default=4)
    parser.add_argument("--delta", type=float, default=0.10)
    parser.add_argument("--refine_start", type=float, default=0.75)
    parser.add_argument("--noise_scale", type=float, default=2.0)
    parser.add_argument("--sccfg", type=float, default=3.0)
    parser.add_argument("--lr", type=float, default=1e-5)
    parser.add_argument("--lambda_x", type=float, default=1.0)
    parser.add_argument("--lambda_sync", type=float, default=1.0)
    parser.add_argument("--ema_decay", type=float, default=0.9999)
    parser.add_argument("--log_every", type=int, default=10)
    return parser.parse_args()


def student_config(max_length):
    cfg = common.model_config(max_length)
    cfg.update(
        per_token_time_conditioning=True,
        per_layer_time_conditioning=True,
    )
    return cfg


def load_model(path, config, device):
    checkpoint = torch.load(path, map_location="cpu", weights_only=False)
    model = ELF_B(**config)
    weights = checkpoint.get("ema_params1", checkpoint["params"])
    missing, unexpected = model.load_state_dict(weights, strict=False)
    if missing or unexpected:
        print(f"load {path}: missing={missing} unexpected={unexpected}")
    return model.to(device)


@torch.no_grad()
def teacher_trajectory(z0, teacher, grid, sccfg):
    cfg = common.SamplingConfig()
    z = z0.clone()
    x_pred = torch.zeros_like(z)
    states = [z.clone()]
    predictions = [x_pred.clone()]
    with torch.amp.autocast(
        "cuda", dtype=torch.bfloat16, enabled=z.device.type == "cuda"
    ):
        for index in range(grid.shape[0] - 1):
            z, x_pred = _ode_step(
                model=teacher,
                z=z,
                t=grid[index].item(),
                t_next=grid[index + 1].item(),
                x_pred_prev=x_pred,
                config=cfg,
                cfg_scale=1.0,
                self_cond_cfg_scale=sccfg,
                cond_seq=None,
                cond_seq_mask=None,
            )
            states.append(z.clone())
            predictions.append(x_pred.clone())
    return torch.stack(states), torch.stack(predictions)


def assemble(trajectory, tau):
    """Positionwise linear interpolation of a (K+1,B,L,D) trajectory."""
    intervals = trajectory.shape[0] - 1
    coordinate = (tau.float() * intervals).clamp(0.0, intervals)
    low = coordinate.floor().long()
    high = (low + 1).clamp(max=intervals)
    weight = (coordinate - low.float()).unsqueeze(-1)
    by_position = trajectory.permute(1, 2, 0, 3)
    gather_shape = (*low.shape, 1, trajectory.shape[-1])
    low_value = torch.gather(
        by_position, 2, low.unsqueeze(-1).unsqueeze(-1).expand(gather_shape)
    ).squeeze(2)
    high_value = torch.gather(
        by_position, 2, high.unsqueeze(-1).unsqueeze(-1).expand(gather_shape)
    ).squeeze(2)
    return low_value + weight * (high_value - low_value)


def time_matrix(global_t, batch, length, delta, refine_start, device, dtype):
    rank = torch.linspace(0.0, 1.0, length, device=device, dtype=dtype)
    offset = 1.0 - 2.0 * rank
    normalized = min(max(float(global_t) / refine_start, 0.0), 1.0)
    envelope = math.sin(math.pi * normalized)
    tau = (float(global_t) + delta * envelope * offset).clamp(0.0, 1.0)
    return tau[None].expand(batch, -1)


def student_transition(student, z, x_prev, tau, tau_next, sccfg):
    model_input = torch.cat([z, x_prev], dim=-1)
    sc = torch.full((z.shape[0],), sccfg, dtype=z.dtype, device=z.device)
    net_out = student(
        model_input,
        tau,
        deterministic=True,
        self_cond_cfg_scale=sc,
        decoder_step_active=None,
    )[0]
    velocity, x_hat = net_out_to_v_x(net_out, z, tau, t_eps=0.05)
    z_next = z + (tau_next - tau).unsqueeze(-1) * velocity
    return z_next, x_hat


def state_loss(predicted, target):
    return ((predicted.float() - target.float()) ** 2).mean()


def update_ema(ema, model, decay):
    with torch.no_grad():
        for name, parameter in model.state_dict().items():
            ema[name].mul_(decay).add_(parameter.detach(), alpha=1.0 - decay)


def save_checkpoint(path, model, ema, step, args):
    path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(
        {
            "params": {name: value.detach().cpu() for name, value in model.state_dict().items()},
            "ema_params1": {name: value.detach().cpu() for name, value in ema.items()},
            "step": step,
            "config": vars(args),
        },
        path,
    )


def main():
    args = parse_args()
    if args.unroll_steps <= 0 or args.unroll_steps > args.teacher_steps:
        raise ValueError("unroll_steps must be in [1, teacher_steps]")
    if args.delta > args.refine_start / math.pi:
        raise ValueError("delta must be <= refine_start/pi")
    device = torch.device(args.device)
    torch.manual_seed(args.seed)
    if device.type == "cuda":
        torch.cuda.manual_seed_all(args.seed)
    common.SamplingConfig.denoiser_noise_scale = args.noise_scale

    teacher_path = Path(args.teacher_checkpoint)
    student_path = Path(args.student_checkpoint)
    teacher = load_model(
        teacher_path, common.model_config(args.max_length), device
    ).eval()
    for parameter in teacher.parameters():
        parameter.requires_grad_(False)
    student = load_model(student_path, student_config(args.max_length), device).train()
    optimizer = torch.optim.AdamW(student.parameters(), lr=args.lr)
    ema = {
        name: value.detach().clone()
        for name, value in student.state_dict().items()
    }
    grid = get_sampling_steps(
        args.teacher_steps, time_schedule="uniform", device=device
    )
    generator = torch.Generator(device=device).manual_seed(args.seed + 1000)
    logs = []

    for step in range(1, args.steps + 1):
        z0 = args.noise_scale * torch.randn(
            args.batch_size,
            args.max_length,
            common.model_config(args.max_length)["text_encoder_dim"],
            generator=generator,
            device=device,
        )
        teacher_states, teacher_predictions = teacher_trajectory(
            z0, teacher, grid, args.sccfg
        )
        max_start = args.teacher_steps - (
            args.unroll_steps if args.mode == "on_policy" else 1
        )
        start_index = int(
            torch.randint(0, max_start + 1, (1,), generator=generator, device=device).item()
        )
        transitions = args.unroll_steps if args.mode == "on_policy" else 1
        on_policy_probability = (
            0.5 * step / args.steps if args.mode == "on_policy" else 0.0
        )

        tau = time_matrix(
            grid[start_index].item(),
            args.batch_size,
            args.max_length,
            args.delta,
            args.refine_start,
            device,
            z0.dtype,
        )
        z_current = assemble(teacher_states, tau)
        x_previous = assemble(teacher_predictions, tau)
        total_state = torch.zeros((), device=device)
        total_x = torch.zeros((), device=device)

        with torch.amp.autocast(
            "cuda", dtype=torch.bfloat16, enabled=device.type == "cuda"
        ):
            for offset in range(transitions):
                next_global = grid[start_index + offset + 1].item()
                tau_next = time_matrix(
                    next_global,
                    args.batch_size,
                    args.max_length,
                    args.delta,
                    args.refine_start,
                    device,
                    z0.dtype,
                )
                target_z = assemble(teacher_states, tau_next)
                target_x = assemble(teacher_predictions, tau)
                predicted_z, predicted_x = student_transition(
                    student, z_current, x_previous, tau, tau_next, args.sccfg
                )
                total_state = total_state + state_loss(predicted_z, target_z)
                total_x = total_x + state_loss(predicted_x, target_x)

                if offset + 1 < transitions:
                    next_teacher_x = assemble(teacher_predictions, tau_next)
                    choose_student = (
                        torch.rand(
                            args.batch_size,
                            1,
                            1,
                            generator=generator,
                            device=device,
                        ) < on_policy_probability
                    )
                    z_current = torch.where(
                        choose_student, predicted_z.detach(), target_z.detach()
                    )
                    x_previous = torch.where(
                        choose_student, predicted_x.detach(), next_teacher_x.detach()
                    )
                    tau = tau_next

            # Synchronous preservation loss at the same starting checkpoint.
            scalar_t = torch.full(
                (args.batch_size, args.max_length),
                grid[start_index].item(),
                dtype=z0.dtype,
                device=device,
            )
            scalar_next = torch.full_like(
                scalar_t, grid[start_index + 1].item()
            )
            sync_z = teacher_states[start_index]
            sync_x = teacher_predictions[start_index]
            predicted_sync_z, _ = student_transition(
                student, sync_z, sync_x, scalar_t, scalar_next, args.sccfg
            )
            sync_loss = state_loss(
                predicted_sync_z, teacher_states[start_index + 1]
            )
            loss = (
                total_state / transitions
                + args.lambda_x * total_x / transitions
                + args.lambda_sync * sync_loss
            )

        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        grad_norm = torch.nn.utils.clip_grad_norm_(student.parameters(), 1.0)
        optimizer.step()
        update_ema(ema, student, args.ema_decay)

        record = {
            "step": step,
            "loss": float(loss.detach()),
            "state_loss": float((total_state / transitions).detach()),
            "x_loss": float((total_x / transitions).detach()),
            "sync_loss": float(sync_loss.detach()),
            "grad_norm": float(grad_norm),
            "on_policy_probability": on_policy_probability,
            "start_index": start_index,
            "local_scale_mean": float(student.local_time_scales.detach().abs().mean()),
        }
        logs.append(record)
        if step == 1 or step % args.log_every == 0:
            print(json.dumps(record))

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    save_checkpoint(output_dir / f"checkpoint_{args.steps}", student, ema, args.steps, args)
    with open(output_dir / "train_metrics.json", "w", encoding="utf-8") as handle:
        json.dump(logs, handle, indent=2)
    print(f"Saved -> {output_dir}")


if __name__ == "__main__":
    main()
