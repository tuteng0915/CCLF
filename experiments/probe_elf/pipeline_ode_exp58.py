def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--device", default="cuda:2")
    parser.add_argument("--ckpt",   default=None)
    args = parser.parse_args()
    device = torch.device(args.device)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    from transformers import AutoModelForCausalLM, AutoTokenizer, T5Tokenizer

    print("Loading GPT-2 PPL model (gpt2-large)...")
    ppl_tok = AutoTokenizer.from_pretrained("gpt2-large")
    if ppl_tok.pad_token is None:
        ppl_tok.pad_token     = ppl_tok.eos_token
        ppl_tok.pad_token_id  = ppl_tok.eos_token_id
    ppl_model = (AutoModelForCausalLM.from_pretrained("gpt2-large", torch_dtype=torch.bfloat16)
                 .to(device).eval())

    print("Loading T5-small encoder...")
    _, encoder = get_encoder("t5-small", dtype=torch.float32)
    encoder = encoder.to(device).eval()
    for p in encoder.parameters():
        p.requires_grad_(False)

    elf_tok = T5Tokenizer.from_pretrained("t5-small")

    print(f"Building {N_COND} prefix/suffix pairs from NLTK gutenberg...")
    cond_data = get_gutenberg_pairs(elf_tok, N_COND)
    print(f"  Got {len(cond_data)} pairs  "
          f"(prefix example: {elf_tok.decode(cond_data[0][0], skip_special_tokens=True)[:80]}...)")

    ckpts = [args.ckpt] if args.ckpt else list(CHECKPOINTS.keys())
    all_results = {}
    for ck in ckpts:
        all_results[ck] = run_ckpt(ck, device, ppl_model, ppl_tok, elf_tok, encoder, cond_data)

    # Save stats (no text bodies)
    save = {ck: {arm: {k: v for k, v in rv.items() if k != "texts"}
                 for arm, rv in cr.items()}
            for ck, cr in all_results.items()}
    out = OUT_DIR / "results.json"
    with open(out, "w") as f:
        json.dump(save, f, indent=2)
    print(f"\nSaved → {out}")

    print("\n=== SUMMARY ===")
    for ck, cr in all_results.items():
        print(f"\n{ck}:")
        for arm, rv in cr.items():
            rl_str = f"  ROUGE-L={rv['rouge_l']:.3f}" if "rouge_l" in rv else ""
            print(f"  {arm:<24} PPL={rv['ppl']:.1f}  D1={rv['d1']:.3f}  D2={rv['d2']:.3f}"
                  f"  I={rv['I']:+.1f}{rl_str}")
        print("  Sample suffix (pipeline_avg_cond):")
        for t in cr.get("pipeline_avg_cond", {}).get("texts", [])[:2]:
            print(f"    > {t[:120]}")

    print("\nReference baselines:")
    print("  EXP-56b kd2 prog_t30_c70 : I=−186 PPL=98  (PPL hacking: D1=0.108, D2=0.416)")
    print("  EXP-56b kd_cr prog_t40   : I=−175 PPL=157 (mild PPL hacking: D1=0.156)")
    print("  Healthy: D1/D2 ≈ standard; ROUGE-L > 0.05")


if __name__ == "__main__":
    main()
