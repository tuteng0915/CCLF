@torch.no_grad()
def decode_z(z, model, device):
    B = z.shape[0]
    z_in = torch.cat([z, torch.zeros_like(z)], dim=-1)
    t1 = torch.ones(B, dtype=z.dtype, device=device)
    sc = torch.ones(B, dtype=z.dtype, device=device)
    with torch.amp.autocast("cuda", dtype=torch.bfloat16, enabled=device.type == "cuda"):
        _, logits, _ = model(z_in, t1, deterministic=True,
                             self_cond_cfg_scale=sc, decoder_step_active=True)
    return logits.argmax(dim=-1)  # (B, N)


@torch.no_grad()
def decode_xpred(x_pred, model, device):
    """Decode from x_pred (for global pipeline trailing positions)."""
    B = x_pred.shape[0]
    z_in = torch.cat([x_pred, torch.zeros_like(x_pred)], dim=-1)
    t1 = torch.ones(B, dtype=x_pred.dtype, device=device)
    sc = torch.ones(B, dtype=x_pred.dtype, device=device)
    with torch.amp.autocast("cuda", dtype=torch.bfloat16, enabled=device.type == "cuda"):
        _, logits, _ = model(z_in, t1, deterministic=True,
                             self_cond_cfg_scale=sc, decoder_step_active=True)
    return logits.argmax(dim=-1)


@torch.no_grad()
def run_standard_ode(z0, model, t_steps, device, cond_seq=None, cond_mask=None):
    z = z0.clone()
    # x_pred_prev init: zeros for uncond, cond_seq for cond (gives model a head start)
    x_pred_prev = (cond_seq.clone().to(z.dtype) if cond_seq is not None
                   else torch.zeros_like(z))
    cfg = _Cfg()
    use_bf16 = cfg.use_bf16 and device.type == "cuda"
    with torch.amp.autocast("cuda", dtype=torch.bfloat16, enabled=use_bf16):
        for i in range(t_steps.shape[0] - 1):
            z, x_pred_prev = _ode_step(
                z=z, t=t_steps[i].item(), t_next=t_steps[i+1].item(),
                x_pred_prev=x_pred_prev, model=model, config=cfg,
                cfg_scale=1.0, self_cond_cfg_scale=SCCFG,
                cond_seq=cond_seq, cond_seq_mask=cond_mask,
            )
    return z, x_pred_prev


@torch.no_grad()
def run_pipeline_ode(z0, model, T, shared_t_mode, device, cond_seq=None, cond_mask=None):
    """
    Pipeline ODE: 2T-1 model calls, active positions staggered by 1 step.
    cond_seq/cond_mask: optional prefix conditioning (handled inside _ode_step).
    """
    cfg = _Cfg()
    B, N, D = z0.shape
    CHUNK = max(1, N // T)
    TOTAL = 2 * T - 1  # 31 for T=16

    z          = z0.clone()
    x_pred_prev = (cond_seq.clone().to(z.dtype) if cond_seq is not None
                   else torch.zeros_like(z))

    pos_idx  = torch.arange(N, device=device)
    group_of = torch.clamp(pos_idx // CHUNK, 0, T - 1)

    use_bf16 = cfg.use_bf16 and device.type == "cuda"
    with torch.amp.autocast("cuda", dtype=torch.bfloat16, enabled=use_bf16):
        for k in range(TOTAL):
            j_min = max(0, k - T + 1)
            j_max = min(T - 1, k)

            if shared_t_mode == "global":
                t      = k / TOTAL
                t_next = (k + 1) / TOTAL
            else:  # "avg"
                t      = ((k - j_max) + (k - j_min)) / (2.0 * T)
                t_next = min(t + 1.0 / T, 1.0)

            z_full, x_pred = _ode_step(
                z=z, t=t, t_next=t_next, x_pred_prev=x_pred_prev,
                model=model, config=cfg,
                cfg_scale=1.0, self_cond_cfg_scale=SCCFG,
                cond_seq=cond_seq, cond_seq_mask=cond_mask,
            )

            active    = (group_of >= j_min) & (group_of <= j_max)
            active_3d = active.unsqueeze(0).unsqueeze(-1).expand(B, N, D)
            z           = torch.where(active_3d, z_full,   z)
            x_pred_prev = torch.where(active_3d, x_pred,   x_pred_prev)

    return z, x_pred_prev


def ids_to_texts_full(ids, tokenizer):
    """Decode full sequence (B, N) → list of str."""
    eos = tokenizer.eos_token_id
    texts = []
    for row in ids.tolist():
        try: row = row[:row.index(eos)]
        except ValueError: pass
        texts.append(tokenizer.decode(row, skip_special_tokens=True))
    return texts


def ids_to_texts_suffix(ids, tokenizer, prefix_len):
    """Decode only suffix positions (B, N) → list of str."""
    suffix_ids = ids[:, prefix_len:]
    texts = []
    for row in suffix_ids.tolist():
        eos = tokenizer.eos_token_id
        try: row = row[:row.index(eos)]
        except ValueError: pass
        texts.append(tokenizer.decode(row, skip_special_tokens=True))
    return texts


# ---------------------------------------------------------------------------
# Data: gutenberg prefix+suffix pairs
# ---------------------------------------------------------------------------

def get_gutenberg_pairs(elf_tok, n_pairs):
    """Return list of (prefix_ids, suffix_ids) using NLTK gutenberg corpus."""
    import nltk
    nltk.download("gutenberg", quiet=True)
    from nltk.corpus import gutenberg

    total_len = PREFIX_LEN + SUFFIX_LEN
    pairs = []
    for fname in gutenberg.fileids():
        raw = gutenberg.raw(fname)
        words = re.split(r"\s+", raw.strip())
        for i in range(0, len(words) - total_len * 2, total_len):
            chunk = " ".join(words[i:i + total_len * 2])
            ids = elf_tok.encode(chunk, add_special_tokens=False)
            if len(ids) >= total_len:
                pairs.append((ids[:PREFIX_LEN], ids[PREFIX_LEN:total_len]))
            if len(pairs) >= n_pairs:
                return pairs
    return pairs


# ---------------------------------------------------------------------------
# Per-checkpoint evaluation
# ---------------------------------------------------------------------------

def run_ckpt(ckpt_name, device, ppl_model, ppl_tok, elf_tok, encoder, cond_data):
    """
    cond_data: list of (prefix_ids, suffix_ids) from gutenberg, length >= N_COND
    """
    print(f"\n{'='*60}\nCheckpoint: {ckpt_name}\n{'='*60}")
    ckpt = torch.load(REPO_ROOT / CHECKPOINTS[ckpt_name], map_location="cpu",
                      weights_only=False)
    model = ELF_B(**MODEL_CFG)
    model.load_state_dict(ckpt["params"], strict=False)
    model.eval().to(device)

    gen = torch.Generator(device=device)
    gen.manual_seed(SEED)
    all_z0 = torch.randn(max(N_UNCOND, N_COND), MAX_LENGTH, 512,
                         generator=gen, device=device)
    t_steps = get_sampling_steps(N_STEPS, time_schedule="uniform", device=device)

    results = {}

    # ---- 1. Unconditional evaluation ----
    print("\n  [Unconditional generation]")
    std_ppl = None
    uncond_arms = [
        ("standard",        None),
        ("pipeline_global", "global"),
        ("pipeline_avg",    "avg"),
    ]
    for arm_name, pipe_mode in uncond_arms:
        texts = []
        for b in range(0, N_UNCOND, BATCH_SIZE):
            z0_b = all_z0[b:b+BATCH_SIZE]
            if pipe_mode is None:
                z, _ = run_standard_ode(z0_b, model, t_steps, device)
                ids  = decode_z(z, model, device)
            else:
                z_out, xp_out = run_pipeline_ode(z0_b, model, T_PIPE, pipe_mode, device)
                ids = (decode_xpred(xp_out, model, device) if pipe_mode == "global"
                       else decode_z(z_out, model, device))
            texts.extend(ids_to_texts_full(ids.cpu(), elf_tok))

        ppl = compute_ppl(texts, ppl_model, ppl_tok, device)
        d1  = compute_distinct(texts, 1)
        d2  = compute_distinct(texts, 2)
        if arm_name == "standard":
            std_ppl = ppl
        I_val = ppl - std_ppl if std_ppl is not None else 0.0
        results[arm_name] = {"ppl": ppl, "I": I_val, "d1": d1, "d2": d2, "texts": texts[:4]}
        suf = f"  I={I_val:+.1f}" if arm_name != "standard" else ""
        print(f"  {arm_name:<24} PPL={ppl:.1f}  D1={d1:.3f}  D2={d2:.3f}{suf}")

    # ---- 2. Build cond_seq from T5 encoder ----
    print(f"\n  [Building cond_seq from T5 encoder ({N_COND} prefixes)]")
    all_cond_seq  = []
    cond_mask_full = torch.zeros(N_COND, MAX_LENGTH, device=device)
    cond_mask_full[:, :PREFIX_LEN] = 1.0
    true_suffix_texts = []

    for b in range(0, N_COND, BATCH_SIZE):
        batch_pairs = cond_data[b:b+BATCH_SIZE]
        bp = len(batch_pairs)
        prefix_batch = [p for p, s in batch_pairs]
        suffix_batch = [s for p, s in batch_pairs]

        true_suffix_texts.extend(
            elf_tok.decode(s[:SUFFIX_LEN], skip_special_tokens=True)
            for s in suffix_batch
        )

        ids_t = torch.zeros(bp, PREFIX_LEN, dtype=torch.long, device=device)
        attn  = torch.zeros(bp, PREFIX_LEN, dtype=torch.long, device=device)
        for j, pid in enumerate(prefix_batch):
            L = min(len(pid), PREFIX_LEN)
            ids_t[j, :L] = torch.tensor(pid[:L], dtype=torch.long, device=device)
            attn[j, :L]  = 1

        latents = encode_text(ids_t, attn, encoder,
                              latent_mean=0.0, latent_std=LATENT_STD)  # (bp, PREFIX_LEN, 512)

        cs_b = torch.zeros(bp, MAX_LENGTH, 512, device=device, dtype=latents.dtype)
        cs_b[:, :PREFIX_LEN, :] = latents
        all_cond_seq.append(cs_b)

    all_cond_seq = torch.cat(all_cond_seq, dim=0)  # (N_COND, MAX_LENGTH, 512)

    # Initialize z: prefix = cond_seq, suffix = noise (model will keep prefix fixed via cond_mask)
    cond_z0 = all_z0[:N_COND].clone()
    cond_z0[:, :PREFIX_LEN, :] = all_cond_seq[:, :PREFIX_LEN, :].to(cond_z0.dtype)

    # ---- 3. Conditioned evaluation ----
    print(f"\n  [Conditioned generation — suffix metrics only]")
    std_cond_ppl = None
    cond_arms = [
        ("standard_cond",        None),
        ("pipeline_global_cond", "global"),
        ("pipeline_avg_cond",    "avg"),
    ]
    for arm_name, pipe_mode in cond_arms:
        suffix_texts = []
        for b in range(0, N_COND, BATCH_SIZE):
            z0_b = cond_z0[b:b+BATCH_SIZE]
            cs_b = all_cond_seq[b:b+BATCH_SIZE].to(torch.bfloat16)
            cm_b = cond_mask_full[b:b+BATCH_SIZE]

            if pipe_mode is None:
                z, _ = run_standard_ode(z0_b, model, t_steps, device, cs_b, cm_b)
                ids  = decode_z(z, model, device)
            else:
                z_out, xp_out = run_pipeline_ode(z0_b, model, T_PIPE, pipe_mode, device, cs_b, cm_b)
                ids = (decode_xpred(xp_out, model, device) if pipe_mode == "global"
                       else decode_z(z_out, model, device))

            suffix_texts.extend(ids_to_texts_suffix(ids.cpu(), elf_tok, PREFIX_LEN))

        ppl  = compute_ppl(suffix_texts, ppl_model, ppl_tok, device)
        d1   = compute_distinct(suffix_texts, 1)
        d2   = compute_distinct(suffix_texts, 2)
        rl   = (sum(rouge_l_f1(h, r) for h, r in
                    zip(suffix_texts, true_suffix_texts[:len(suffix_texts)]))
                / max(len(suffix_texts), 1))

        if arm_name == "standard_cond":
            std_cond_ppl = ppl
        I_val = ppl - std_cond_ppl if std_cond_ppl is not None else 0.0
        results[arm_name] = {"ppl": ppl, "I": I_val, "d1": d1, "d2": d2,
                              "rouge_l": rl, "texts": suffix_texts[:4]}
        suf = f"  I={I_val:+.1f}" if arm_name != "standard_cond" else ""
        print(f"  {arm_name:<24} PPL={ppl:.1f}  D1={d1:.3f}  D2={d2:.3f}"
              f"  ROUGE-L={rl:.3f}{suf}")

    del model
    torch.cuda.empty_cache()
    return results


