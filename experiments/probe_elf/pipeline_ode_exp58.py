#!/usr/bin/env python3
"""
EXP-58: Pipeline ODE (Diffusion Forcing Approximation, inference-only)
+ Conditioned generation evaluation to guard against PPL hacking

Unconditional arms: standard (ODE-32), pipeline_global, pipeline_avg
  - Metrics: PPL (GPT-2), D1/D2 (diversity), I (PPL improvement)

Conditioned arms: standard_cond, pipeline_global_cond, pipeline_avg_cond
  - Prefix: 64 real tokens from NLTK gutenberg (via T5 encoder → x0)
  - Suffix: 64 tokens generated by model
  - Metrics: suffix-PPL, ROUGE-L vs true suffix, D1/D2 on generated suffix
  - ROUGE-L > 0.05 and D1/D2 near standard_cond → healthy generation
  - PPL collapse + D1/D2 drop → PPL hacking

Models: kd_cr, kd2
N_UNCOND=256, N_COND=128, T_PIPE=16 (31 model calls), ODE-32 baseline
seed=42, max_length=128, latent_std=0.2

Usage:
    cd models/ELF-torch
    conda run -n elf python3 experiments/probe_elf/pipeline_ode_exp58.py --device cuda:2
"""

